-- 巴尔扎罗斯护卫专用单位：不能继续使用通用召唤物壳，否则物编头像、攻击类型和原生普攻都会丢失。
local function applyBalzarothGuardCommon(unit, name, modelFile, icon, hp, collision)
  unit:setName(name)
  unit:setTooltipBasic(name)
  unit:setTooltipExtended('巴尔扎罗斯熔核封印护卫。')
  unit:setDescription(name)
  unit:setModelFile(modelFile)
  unit:setModelFileExtraVersions('0')
  unit:setIconGameInterface(icon)
  unit:setIconScoreScreen(icon)
  unit:setNormalAbilities('')
  unit:setUnitSoundSet('')
  unit:setUnitClassification('ancient')
  unit:setRace(Race.Demon)
  unit:setMovementType(MovementType.Foot)
  unit:setMovementHeightMinimum(0.0)
  unit:setMovementHeight(0.0)
  unit:setSpeedBase(300)
  unit:setSpeedMinimum(0)
  unit:setSpeedMaximum(522)
  unit:setTurnRate(0.7)
  unit:setPropulsionWindowdegrees(60.0)
  unit:setCollisionSize(collision)
  unit:setScalingValue(1.0)
  unit:setSelectionScale(1.2)
  unit:setSightRadiusDay(1400)
  unit:setSightRadiusNight(1400)
  unit:setAcquisitionRange(1200.0)
  unit:setLevel(48)
  unit:setHitPointsMaximumBase(hp)
  unit:setHitPointsRegenerationType('always')
  unit:setHitPointsRegenerationRate(hp * 0.008)
  unit:setManaMaximum(1000)
  unit:setManaInitialAmount(1000)
  unit:setManaRegeneration(10.0)
  unit:setDefenseBase(20)
  unit:setDefenseUpgradeBonus(0)
  unit:setArmorType(ArmorType.Hero)
  unit:setPointValue(0)
  unit:setPriority(9)
  unit:setFormationRank(2)
  unit:setCanFlee(false)
  unit:setCanDropItemsOnDeath(false)
  unit:setFoodCost(0)
  unit:setFoodProduced(0)
  unit:setGoldCost(0)
  unit:setLumberCost(0)
  unit:setBuildTime(0)
  unit:setRepairTime(0)
  unit:setRepairGoldCost(0)
  unit:setRepairLumberCost(0)
  unit:setGoldBountyAwardedBase(0)
  unit:setGoldBountyAwardedNumberofDice(0)
  unit:setGoldBountyAwardedSidesperDie(0)
  unit:setLumberBountyAwardedBase(0)
  unit:setLumberBountyAwardedNumberofDice(0)
  unit:setLumberBountyAwardedSidesperDie(0)
end

