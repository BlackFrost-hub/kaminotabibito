import type { 攻击效果上下文 } from "../08．攻击效果/00．公共/00．攻击效果类型";
import { 注册攻击效果配置 } from "../08．攻击效果/00．公共/02．攻击效果注册表";
import { 取攻击力 } from "../08．攻击效果/00．公共/01．攻击效果工具";

const { 施加燃烧效果 } = require("系统.03．技能系统.00．技能模板+函数.01．技能函数.19．拓展效果.01．debuff.03．燃烧") as {
  施加燃烧效果: (this: void, source: any, target: any, 参数: any) => void;
};

function 执行炽热之弹矢燃烧(this: void, 上下文: 攻击效果上下文): void {
  施加燃烧效果(上下文.source, 上下文.target, {
    持续模式: "刷新",
    持续时间: 3,
    每秒伤害: 100 + 取攻击力(上下文.source) * 0.2,
    伤害来源名称: "炽热之弹矢",
  });
}

注册攻击效果配置({
  装备名: "炽热之弹矢",
  触发侧: "攻击者",
  效果类型: "持续伤害",
  仅普通攻击: true,
  攻击者类型: "远程",
  自定义执行: 执行炽热之弹矢燃烧,
});

