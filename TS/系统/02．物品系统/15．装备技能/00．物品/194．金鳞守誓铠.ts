// 祖地秘境·金鳞执刑官掉落：金鳞守誓铠（被动·重鳞）
// 重鳞：持有者受击时叠加重鳞，每层护甲+4，最多5层；6秒未受击后清空。
// 实现选型：注册最终伤害触发模板（持有者=受击者）+ 单位时限数值叠层 + 临时属性效果托管器（安魂守墓灯模式）。

import { 注册最终伤害触发模板 } from "../../../03．技能系统/00．技能模板+函数/00．技能模板/08．装备触发模板/03．最终伤害触发模板";
import { 创建单位时限数值 } from "../../../03．技能系统/00．技能模板+函数/04．机制组件/09．装备通用机制/index";
import { 创建单位临时属性效果托管器 } from "../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/19．临时属性效果";
import { registerManualBuff } from "../../../05．Buff系统/00．Buff系统";
import { 常规BuffID } from "../../../05．Buff系统/03．Buff表/00．Buff登记";
import { 祖地秘境战利品装备名 } from "../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/11．装备常量";

const 重鳞每层护甲 = 4;
const 重鳞最大层数 = 5;
const 重鳞窗口秒 = 6;
const 重鳞层数 = 创建单位时限数值("金鳞守誓铠-重鳞层数");
const 重鳞属性效果 = 创建单位临时属性效果托管器();

function 清除重鳞属性(this: void, unit: any, _buffID: string, _row: any): void {
    重鳞层数.清空(unit);
    重鳞属性效果.清除(unit);
}

function on重鳞受击(this: void, event: any): void {
    const unit = event.目标;
    const 层数 = Math.min((重鳞层数.读取(unit) ?? 0) + 1, 重鳞最大层数);
    // 先刷新 Buff（移除旧行会回调清空层数与托管器），再重写层数、施加新属性，保证叠层正确。
    registerManualBuff(unit, 常规BuffID.金鳞守誓铠_重鳞, 重鳞窗口秒, 层数 * 重鳞每层护甲, {
        sourceUnit: unit,
        effectSourceName: 祖地秘境战利品装备名.金鳞守誓铠,
        effectSourceType: "装备",
        onRemove: 清除重鳞属性,
    });
    重鳞层数.写入(unit, 层数, 重鳞窗口秒);
    重鳞属性效果.施加(unit, 0, [
        { 类型: "护甲", 数值: 层数 * 重鳞每层护甲 },
    ]);
}

注册最终伤害触发模板({
    名称: "金鳞守誓铠-重鳞",
    装备名: 祖地秘境战利品装备名.金鳞守誓铠,
    持有者: "受击者",
    要求双方存活: false,
    on触发: on重鳞受击,
});

export {};
