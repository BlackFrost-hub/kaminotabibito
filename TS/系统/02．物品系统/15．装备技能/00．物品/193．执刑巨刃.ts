// 祖地秘境·金鳞执刑官掉落：执刑巨刃（被动·处决）
// 处决：纯普通攻击命中当前生命值不高于40%的敌人时，额外造成攻击力×30%的物理伤害。
// 实现选型：配置型攻击效果注册（幽影匕首注册表模式），概率计算按目标低血判定 0/1，仅普通攻击。

import { 注册攻击效果配置 } from "../08．攻击效果/00．公共/02．攻击效果注册表";
import { 取当前生命, 取最大生命, 祖地秘境战利品装备名 } from "../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/07．装备辅助";

const 处决斩杀线 = 0.4;
const 处决攻击系数 = 0.3;
const 处决特效 = "Common\\Effect\\Element\\Light\\lightnova.mdx";

function 计算执刑巨刃触发概率(this: void, ctx: any): number {
    const target = ctx.target;
    if (target == null || target === 0) return 0;
    return 取当前生命(target) / 取最大生命(target) <= 处决斩杀线 ? 1 : 0;
}

注册攻击效果配置({
    装备名: 祖地秘境战利品装备名.执刑巨刃,
    触发侧: "攻击者",
    效果类型: "额外伤害",
    仅普通攻击: true,
    概率计算: 计算执刑巨刃触发概率,
    攻击系数: 处决攻击系数,
    伤害类型: "物理",
    特效: 处决特效,
});

