import { 单位有效存活, 取单位攻击力, 造成伤害事件伤害, 伤害事件伤害类型, 播放单位特效 } from "../04．伤害事件/00．公共/01．伤害事件工具";

const { 注册最终伤害触发模板 } = require("系统.03．技能系统.00．技能模板+函数.00．技能模板.08．装备触发模板.03．最终伤害触发模板") as {
  注册最终伤害触发模板: (this: void, 配置: any) => any;
};

const 腐化核心冷却秒数 = 2;
const 腐化核心攻击力系数 = 0.5;
const 腐化核心特效 = "Abilities\\Spells\\Other\\AcidBomb\\BottleImpact.mdl";

function on腐化核心法杖最终伤害(this: void, event: any): void {
  if (!单位有效存活(event.攻击者) || !单位有效存活(event.目标)) return;
  播放单位特效(event.目标, 腐化核心特效, "origin", 1);
  造成伤害事件伤害(event.攻击者, event.目标, 取单位攻击力(event.攻击者) * 腐化核心攻击力系数, 伤害事件伤害类型.毒素);
}

注册最终伤害触发模板({
  名称: "腐化核心法杖",
  装备名: "腐化核心法杖",
  持有者: "攻击者",
  伤害过滤: "技能",
  冷却秒数: 腐化核心冷却秒数,
  冷却标签: "腐化核心法杖:腐化核心",
  冷却前缀: "米亚战利品",
  on触发: on腐化核心法杖最终伤害,
});

