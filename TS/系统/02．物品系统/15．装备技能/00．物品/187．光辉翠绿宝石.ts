import { 创建次数型伤害免疫 } from '../../../03．技能系统/00．技能模板+函数/04．机制组件/08．机制触发/08．次数型伤害免疫';
import { 创建句柄上下文托管器 } from '../../../03．技能系统/00．技能模板+函数/04．机制组件/09．装备通用机制/24．句柄上下文托管';
import {
    取装备物品ID,
    播放单位特效,
    四Boss战利品装备名,
    四Boss装备特效,
} from '../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/07．装备辅助';
const 防护 = 创建句柄上下文托管器<any>('光辉翠绿宝石');
function 刷新翠绿防护(this: void, unit: any): void {
    const old = 防护.取出(unit);
    if (old != null && old.是否生效()) old.取消();
    const shield = 创建次数型伤害免疫({
        名称: '光辉翠绿体',
        单位: unit,
        免疫类型: '物理伤害',
        免疫次数: 1,
        持续秒: 22,
        最低伤害: 800,
        最低伤害占最大生命比例: 0.08,
        过滤伤害: (c) =>
            c.isDotDamage !== true &&
            c.isReflectedDamage !== true &&
            c.isDamageTransfer !== true &&
            c.isEquipmentSkillDamage !== true,
        on抵挡: (e) => 播放单位特效(四Boss装备特效.翠绿护盾, e.单位, 'origin', 1.2, 0.32),
    });
    防护.写入(unit, shield);
    播放单位特效(四Boss装备特效.翠绿护盾, unit, 'origin', 1, 0.25);
}
注册持有战斗周期模板({
    名称: '光辉翠绿宝石-周期防护',
    物品类型ID: 取装备物品ID(四Boss战利品装备名.光辉翠绿宝石),
    周期秒: 20,
    on获取: (e) => {
        if (e.前次数量 <= 0) 刷新翠绿防护(e.单位);
    },
    on丢弃: (e) => {
        if (e.持有数量 <= 0) {
            const c = 防护.取出(e.单位);
            if (c != null && c.是否生效()) c.取消();
        }
    },
    on周期: (e) => 刷新翠绿防护(e.单位),
});
export {};
