import { 创建事件叠层状态 } from '../../../03．技能系统/00．技能模板+函数/04．机制组件/01．层数状态/05．事件叠层状态';
import { 施加临时属性效果 } from '../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/19．临时属性效果';
import {
    单位持有装备,
    取当前生命,
    取最大生命,
    开始通用护盾,
    播放单位特效,
    四Boss战利品装备名,
    四Boss装备特效,
} from '../../../03．技能系统/00．技能模板+函数/01．技能函数/20．物品辅助/07．装备辅助';
const 血晶 = 创建事件叠层状态({
    状态ID: '真祖女武神血铠-血晶',
    最大层数: 3,
    触发来源: '受到伤害',
    内置CD秒: 2,
    持续模式: '刷新持续时间',
    层持续秒: 12,
    过滤事件: (e) =>
        单位持有装备(e.单位, 四Boss战利品装备名.真祖女武神血铠) &&
        (e.伤害值 ?? 0) >= 取最大生命(e.单位) * 0.06 &&
        e.伤害快照?.isDotDamage !== true &&
        e.伤害快照?.isReflectedDamage !== true &&
        e.伤害快照?.isDamageTransfer !== true &&
        e.伤害快照?.isEquipmentSkillDamage !== true,
    on事件触发: function on血晶获得(this: void, e, newLayers): void {
        播放单位特效(四Boss装备特效.血晶球壳, e.单位, 'origin', 1, 0.22);
        if (取当前生命(e.单位) / 取最大生命(e.单位) > 0.35) return;
        const layers = 血晶.消耗全部(e.单位, '血宴武装');
        if (layers <= 0) return;
        开始通用护盾(e.单位, e.单位, 取最大生命(e.单位) * (0.05 + layers * 0.04), 6, '血宴武装');
        施加临时属性效果(e.单位, 6000, [{ 类型: '攻速', 数值: layers * 0.18 }]);
        播放单位特效(四Boss装备特效.血晶重构, e.单位, 'origin', 1.5, 0.32);
    },
});
export {};
