const 怨火核心碎片冷却秒数 = 2;
const 怨火核心碎片攻击力系数 = 1;

function on怨火核心碎片最终伤害(this: void, event: any): void {
  if (!单位有效存活(event.攻击者) || !单位有效存活(event.目标)) return;
  造成伤害事件伤害(event.攻击者, event.目标, 取单位攻击力(event.攻击者) * 怨火核心碎片攻击力系数, 伤害事件伤害类型.暗影突袭);
}

注册最终伤害触发模板({
  名称: "怨火核心碎片",
  装备名: "怨火核心碎片",
  持有者: "攻击者",
  伤害过滤: "技能",
  冷却秒数: 怨火核心碎片冷却秒数,
  冷却标签: "怨火核心碎片:怨火灼痕",
  冷却前缀: "第三章主线Boss战利品",
  on触发: on怨火核心碎片最终伤害,
});

