export function 读取动态矩形区域配置(this: void, 键: string): 动态矩形区域配置 | undefined {
  const 直接配置 = 动态矩形区域配置表[键];
  if (直接配置 != null) return 直接配置;
  for (const 组键 in 动态矩形区域组配置表) {
    const 子配置 = 动态矩形区域组配置表[组键].子区域[键];
    if (子配置 != null) return 子配置;
  }
  return undefined;
}

export function 读取动态矩形区域组子区域键(this: void, 组键: string, 用途?: "全部" | "背景音乐"): string[] {
  const 组配置 = 动态矩形区域组配置表[组键];
  if (组配置 == null) return [];
  if (用途 === "背景音乐" && 组配置.背景音乐子区域 != null) {
    return 组配置.背景音乐子区域;
  }
  const 结果: string[] = [];
  for (const 子键 in 组配置.子区域) {
    结果.push(子键);
  }
  return 结果;
}
