/** 剧情进度对应的引导配置 */
export interface 进度配置 {
  /** 提示文本（直接使用 文本常量3.wts STRING 293~317） */
  提示文本: string;
  /** 固定镜头目标 X（与 镜头跟随单位 二选一） */
  镜头X?: number;
  /** 固定镜头目标 Y（与 镜头跟随单位 二选一） */
  镜头Y?: number;
  /** 语义单位引用，如 "主线NPC.蛇人族藏品管家"（与固定坐标二选一） */
  镜头跟随单位?: string;
}
