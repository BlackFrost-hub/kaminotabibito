/**
 * 主线引导配置表
 *
 * 剧情进度 -> 提示文本 / 镜头目标
 * 进度 0 保留旧引导；进度 1 及之后统一读取主线节点配置。
 *
 * 进度映射规则（按旧 JASS）：
 *  - 剧情进度 < 1 使用 0
 *  - 进度 1 及之后直接使用进度值
 */

import type { 进度配置 } from "./00．主线引导类型";
import { 获取主线节点配置 } from "../00．剧情系统核心工具/09．主线节点配置";

const { 读取剧情进度 } = require("系统.11．剧情系统.01．主线任务.00．剧情系统核心工具.01．剧情动作上下文") as {
  读取剧情进度: (this: void) => number;
};

// 进度 0 仍使用旧文本常量。
const STRING_293 = "|cffffff00『主线引导』|r：穿过|cffff9900山谷|r前往|cffffcc99西里尔村落|r";

/** 进度 -> 配置映射表 */
const 进度配置表: Record<number, 进度配置 | undefined> = {};

// 进度 0（< 1 时使用）：STRING 293，镜头 -29104.80, -27527.10
进度配置表[0] = {
  提示文本: STRING_293,
  镜头X: -29104.80,
  镜头Y: -27527.10,
};

function 加载主线节点引导配置(this: void, 起始进度: number, 结束进度: number): void {
  for (let 进度 = 起始进度; 进度 <= 结束进度; 进度++) {
    const 节点 = 获取主线节点配置(进度);
    if (节点 == null) continue;
    const 配置: 进度配置 = { 提示文本: 节点.提示文本 };
    if (节点.引导 != null) {
      配置.镜头X = 节点.引导.镜头X;
      配置.镜头Y = 节点.引导.镜头Y;
      配置.镜头跟随单位 = 节点.引导.镜头跟随单位;
    }
    进度配置表[进度] = 配置;
  }
}

export function 刷新主线节点引导配置(this: void, 进度: number): void {
  const 节点 = 获取主线节点配置(进度);
  if (节点 == null) {
    进度配置表[进度] = undefined;
    return;
  }
  const 配置: 进度配置 = { 提示文本: 节点.提示文本 };
  if (节点.引导 != null) {
    配置.镜头X = 节点.引导.镜头X;
    配置.镜头Y = 节点.引导.镜头Y;
    配置.镜头跟随单位 = 节点.引导.镜头跟随单位;
  }
  进度配置表[进度] = 配置;
}

// 全部已配置主线进度的任务文本和镜头统一来自主线节点配置。
加载主线节点引导配置(1, 49);

/**
 * 根据剧情进度获取配置
 * 进度 < 1 时使用 0；否则直接使用进度值
 */
export function 获取进度配置(this: void): 进度配置 | undefined {
  const 进度 = 读取剧情进度();
  const key = 进度 < 1 ? 0 : 进度;
  return 进度配置表[key];
}
