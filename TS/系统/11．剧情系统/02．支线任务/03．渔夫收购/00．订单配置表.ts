/**
 * 默洛克渔夫 · 渔获收购订单配置
 *
 * 设计要点：
 * - 渔夫只收熔岩鱼（I0AT 赤魔鱼 / I0AU 熔岩食鱼 / I0AV 熔岩灵鱼 / I0AW 熔岩焰鱼）。
 * - 订单**从苛刻到宽松排列**：结算时按数组顺序取第一个「完全满足」的订单，
 *   因此大单不会被小单吃掉（必须把要求高的排前面）。
 * - 奖励**不在任务界面公示**，只由渔夫在提交时开口说；金币是保底，装备是"他犹豫一下才摸出来的东西"。
 */

/** 单个指定需求项。 */
export interface 渔夫需求项 {
  物品ID: string;
  数量: number;
}

export interface 渔夫订单 {
  键: string;
  /** 指定鱼种需求；每种都要够。 */
  指定需求?: readonly 渔夫需求项[];
  /** 额外再从任意熔岩鱼里凑 N 条（用于"随便什么鱼都行"的订单）。 */
  任意数量?: number;
  金币: number;
  /** 有值则额外给一件装备。 */
  装备ID?: string;
   /** 提交时的渔夫台词。 */
  提交对白: string;
}

