function 读取菲利斯剑气灵斩冷却(this: void, unit: any): number {
  const context = 获取或创建菲利斯上下文(unit);
  return context != null && context.当前领袖光环低血
    ? 菲利斯数值与表现配置.剑气灵斩.低血冷却秒
    : 菲利斯数值与表现配置.剑气灵斩.冷却秒;
}

function 读取菲利斯全力封印斩冷却(this: void, _unit: any): number {
  const config = 菲利斯数值与表现配置.全力封印斩;
  const 冷却秒 = config.基础冷却秒 - config.每难度冷却减少秒 * 取难度();
  return 冷却秒 > 10 ? 冷却秒 : 10;
}

