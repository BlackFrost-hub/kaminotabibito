/**
 * 护盾优先级排序
 *
 * 排序规则：
 * 1. 类型优先级：专用护盾（物理/魔法）> 通用护盾
 * 2. 抵挡优先级：数值越高越先被打掉（破碎有收益的护盾优先级高）
 * 3. 到期时间：最早到期的优先（同优先级时）
 */

import { 护盾实例, 护盾类型, 伤害信息 } from "./01．护盾类型";

/**
 * 对护盾列表按优先级排序（返回新数组，不修改原数组）
 *
 * 排序规则：
 * 1. 类型优先级 降序（专用 > 通用）
 * 2. 抵挡优先级 降序（高优先级先被打）
 * 3. 剩余时间 升序（最早到期先被打）
 */
export function 排序护盾列表(护盾列表: 护盾实例[]): 护盾实例[] {
  return [...护盾列表].sort((a, b) => {
    // 1. 类型优先级：降序
    if (a.类型优先级 !== b.类型优先级) {
      return b.类型优先级 - a.类型优先级;
    }
    // 2. 抵挡优先级：降序
    if (a.抵挡优先级 !== b.抵挡优先级) {
      return b.抵挡优先级 - a.抵挡优先级;
    }
    // 3. 剩余时间：升序（最早到期优先）
    // 永久护盾（剩余时间=0）排在最后
    const aTime = a.剩余时间 > 0 ? a.剩余时间 : Infinity;
    const bTime = b.剩余时间 > 0 ? b.剩余时间 : Infinity;
    return aTime - bTime;
  });
}

/**
 * 筛选可匹配伤害类型的护盾
 *
 * 规则：
 * - 通用护盾可吸收所有伤害（包括真实伤害）
 * - 物理/魔法护盾只吸收对应大类伤害
 * - 属性护盾只吸收对应属性伤害
 */
export function 筛选可匹配护盾(护盾列表: 护盾实例[], 伤害: 伤害信息): 护盾实例[] {
  return 护盾列表.filter(实例 => {
    // 通用护盾可吸收所有伤害
    if (实例.类型 === 护盾类型.通用) return true;
    // 物理护盾只吸收物理伤害
    if (实例.类型 === 护盾类型.物理 && 伤害.是物理伤害) return true;
    // 魔法护盾只吸收魔法伤害
    if (实例.类型 === 护盾类型.魔法 && 伤害.是魔法伤害) return true;
    if (实例.类型 === 护盾类型.强化 && 伤害.是强化伤害 === true) return true;
    if (实例.类型 === 护盾类型.金 && 伤害.是金属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.木 && 伤害.是木属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.水 && 伤害.是水属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.火 && 伤害.是火属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.冰 && (伤害.是冰属性伤害 === true || 伤害.是水属性伤害 === true)) return true;
    if (实例.类型 === 护盾类型.雷 && 伤害.是雷属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.风 && (伤害.是风属性伤害 === true || 伤害.是木属性伤害 === true)) return true;
    if (实例.类型 === 护盾类型.暗 && 伤害.是暗属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.光 && 伤害.是光属性伤害 === true) return true;
    if (实例.类型 === 护盾类型.毒 && (伤害.是毒属性伤害 === true || 伤害.是金属性伤害 === true)) return true;
    return false;
  });
}

/**
 * 获取按优先级排序的可匹配护盾列表
 */
export function 获取可匹配护盾列表(护盾列表: 护盾实例[], 伤害: 伤害信息): 护盾实例[] {
  const 匹配列表 = 筛选可匹配护盾(护盾列表, 伤害);
  return 排序护盾列表(匹配列表);
}

