/**
 * 移除指定护盾
 */
export function 移除护盾(护盾ID: number): boolean {
  const 实例 = 获取护盾实例(护盾ID);
  if (实例 == null) return false;

  const 单位 = 实例.单位;
  const 单位ID = 实例.单位ID;

  删除护盾实例(护盾ID);

  // 触发结束回调
  if (typeof 实例.结束回调 === "function") {
    实例.结束回调(单位, 护盾ID, "手动移除");
  }

  // 检查是否还有护盾，没有则删除护盾条
  if (!单位是否有护盾(单位ID)) {
    删除护盾条(单位);
  }

  return true;
}

/**
 * 移除单位的所有护盾
 */
export function 移除单位全部护盾(单位: any): void {
  const 单位ID = 取句柄ID(单位);
  if (单位ID === 0) return;

  const 删除列表 = 删除单位所有护盾(单位ID);
  for (const 实例 of 删除列表) {
    if (typeof 实例.结束回调 === "function") {
      实例.结束回调(单位, 实例.id, "手动移除");
    }
  }

  删除护盾条(单位);
}

