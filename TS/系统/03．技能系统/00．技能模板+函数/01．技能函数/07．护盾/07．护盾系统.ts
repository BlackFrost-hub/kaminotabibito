/**
 * 为单位创建护盾
 *
 * @param 单位 目标单位
 * @param 参数 护盾参数
 * @returns 护盾ID，失败返回 0
 */
export function 开始护盾(单位: any, 参数: 护盾参数): number {
  确保初始化();

  if (单位 == null || 单位 === 0) return 0;
  if (参数.数值 <= 0) return 0;

  const 实例 = 创建护盾实例(单位, 参数);
  if (实例 == null) return 0;

  // 创建/更新护盾条
  if (实例.显示护盾条) {
    尝试注册自定义头顶血条(单位);
  }

  // 触发开始回调
  if (typeof 实例.开始回调 === "function") {
    实例.开始回调(单位, 实例.id);
  }

  通知获得护盾事件(实例.来源单位 ?? 单位, 单位, 实例.当前值, 实例.标签, 参数);

  return 实例.id;
}

export function 开始属性护盾(单位: any, 属性: 护盾属性类型, 参数: 护盾参数): number {
  return 开始护盾(单位, {
    ...参数,
    类型: 护盾属性转类型(属性),
  });
}

