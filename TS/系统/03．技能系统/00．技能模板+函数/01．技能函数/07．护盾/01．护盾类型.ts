/**
 * 护盾类型定义
 *
 * 定义护盾类型枚举、优先级常量、回调类型
 */

// ==========================================================================================
// 护盾类型枚举
// ==========================================================================================

/** 护盾类型 */
export enum 护盾类型 {
  /** 通用护盾 - 可吸收所有类型伤害 */
  通用 = 0,
  /** 物理护盾 - 优先吸收物理伤害 */
  物理 = 1,
  /** 魔法护盾 - 优先吸收魔法伤害 */
  魔法 = 2,
}

// ==========================================================================================
// 优先级常量
// ==========================================================================================

/** 类型优先级：专用护盾 > 通用护盾 */
export const 类型优先级: Record<护盾类型, number> = {
  [护盾类型.物理]: 100,
  [护盾类型.魔法]: 100,
  [护盾类型.通用]: 50,
};

/** 默认抵挡优先级 */
export const 默认抵挡优先级 = 50;

// ==========================================================================================
// 回调类型
// ==========================================================================================

/** 护盾开始回调 */
export type 护盾开始回调 = (this: void, 单位: any, 护盾ID: number) => void;

/** 护盾破碎回调（护盾值归零） */
export type 护盾破碎回调 = (this: void, 单位: any, 护盾ID: number, 吸收伤害: number) => void;

/** 护盾到期回调（持续时间结束） */
export type 护盾到期回调 = (this: void, 单位: any, 护盾ID: number) => void;

/** 护盾结束回调（任何形式结束） */
export type 护盾结束回调 = (this: void, 单位: any, 护盾ID: number, 原因: 护盾结束原因) => void;

/** 护盾结束原因 */
export type 护盾结束原因 = "破碎" | "到期" | "手动移除" | "单位死亡";

// ==========================================================================================
// 护盾参数接口
// ==========================================================================================

/** 创建护盾参数 */
export interface 护盾参数 {
  /** 护盾类型 */
  类型?: 护盾类型;
  /** 护盾数值 */
  数值: number;
  /** 持续时间（秒），0 或不传表示永久 */
  持续时间?: number;
  /** 来源单位 */
  来源单位?: any;
  /** 类型优先级（覆盖默认） */
  类型优先级?: number;
  /** 抵挡优先级（数值越高越先被打掉） */
  抵挡优先级?: number;
  /** 是否显示护盾条，默认 true */
  显示护盾条?: boolean;
  /** 是否可驱散，默认 true */
  可驱散?: boolean;
  /** 自定义标签 */
  标签?: string;
  /** 开始回调 */
  开始回调?: 护盾开始回调;
  /** 破碎回调 */
  破碎回调?: 护盾破碎回调;
  /** 到期回调 */
  到期回调?: 护盾到期回调;
  /** 结束回调 */
  结束回调?: 护盾结束回调;
}

// ==========================================================================================
// 护盾实例接口
// ==========================================================================================

/** 护盾实例 */
export interface 护盾实例 {
  /** 唯一ID */
  id: number;
  /** 所属单位 */
  单位: any;
  /** 单位句柄ID */
  单位ID: number;
  /** 来源单位 */
  来源单位?: any;
  /** 护盾类型 */
  类型: 护盾类型;
  /** 初始值 */
  初始值: number;
  /** 当前值 */
  当前值: number;
  /** 总持续时间 */
  总持续时间: number;
  /** 剩余时间 */
  剩余时间: number;
  /** 类型优先级 */
  类型优先级: number;
  /** 抵挡优先级 */
  抵挡优先级: number;
  /** 是否显示护盾条 */
  显示护盾条: boolean;
  /** 是否可驱散 */
  可驱散: boolean;
  /** 自定义标签 */
  标签?: string;
  /** 开始回调 */
  开始回调?: 护盾开始回调;
  /** 破碎回调 */
  破碎回调?: 护盾破碎回调;
  /** 到期回调 */
  到期回调?: 护盾到期回调;
  /** 结束回调 */
  结束回调?: 护盾结束回调;
}

// ==========================================================================================
// 伤害信息接口（供伤害结算使用）
// ==========================================================================================

/** 伤害信息 */
export interface 伤害信息 {
  /** 目标单位 */
  目标: any;
  /** 攻击者 */
  攻击者: any;
  /** 伤害值 */
  伤害值: number;
  /** 是否物理伤害 */
  是物理伤害: boolean;
  /** 是否魔法伤害 */
  是魔法伤害: boolean;
  /** 是否真实伤害 */
  是真实伤害: boolean;
  /** 是否普攻 */
  是普攻: boolean;
}

export {};
