/**
 * 战斗技能实例生命周期工厂自检（H-01）
 *
 * 默认关闭；进图后在测试控制台手动调用 运行H01自检()。
 * 覆盖测试矩阵：
 *   1. 同单位连续创建两个同类实例（并存 + 代次递增）
 *   2. 旧实例延迟回调晚于新实例创建（仍有效() = false，不操作新实例）
 *   3. 施法者死亡（全部实例按"施法者死亡"收束）
 *   4. 目标先死亡（按"目标死亡"收束）
 *   5. 主动中断后再次施法（中断收束 + 新实例代次 +1）
 *   6. 重复调用清理（幂等，结束回调只执行一次）
 */

import {
  创建战斗技能实例,
  查询战斗技能实例,
  按ID查询战斗技能实例,
  结束单位战斗技能实例,
  校验单位替换并收束,
} from "../../04．机制组件/10．复杂战斗通用机制/27．战斗技能实例生命周期工厂";

const jass = require("jass.common") as any;
const print = (jass.print ?? ((_s: string) => {})) as (this: void, s: string) => void;
const { stringToFourCCSafe } = require("lib.扩展函数.封装函数.01．通用工具.01．FourCC转换安全版") as {
  stringToFourCCSafe: (this: void, value: string) => number;
};
const 农民单位类型 = stringToFourCCSafe("hpea");

function 自检输出(this: void, 消息: string): void {
  print("[H-01自检] " + 消息);
}

function 断言(this: void, 条件: boolean, 消息: string): void {
  if (条件) {
    自检输出("通过: " + 消息);
  } else {
    自检输出("失败: " + 消息);
  }
}

export function 运行H01自检(this: void): void {
  // 造两个测试单位
  const 施法者 = jass.CreateUnit(jass.Player(0), 农民单位类型, 0, 0, 0);
  const 目标 = jass.CreateUnit(jass.Player(1), 农民单位类型, 200, 0, 0);
  if (施法者 == null || 施法者 === 0 || 目标 == null || 目标 === 0) {
    自检输出("无法创建测试单位，中止");
    return;
  }

  let 回调计数1 = 0;

  // ---- 1. 同单位连续两个同类实例 ----
  const 实例1 = 创建战斗技能实例({
    技能键: "测试技能",
    施法者,
    目标,
    数据: { 序号: 1 },
    结束回调: function (this: void, _原因, _控制器): void {
      回调计数1++;
    },
  });
  const 实例2 = 创建战斗技能实例({ 技能键: "测试技能", 施法者, 数据: { 序号: 2 } });
  断言(查询战斗技能实例(施法者, "测试技能").length === 2, "同单位同类实例并存 = 2");
  断言(实例2.代次 === 实例1.代次 + 1, "代次递增");

  // ---- 2. 旧实例延迟回调晚于新实例创建 ----
  断言(实例1.仍有效() === false, "旧实例代次失效（仍有效 = false）");
  断言(实例2.仍有效() === true, "新实例仍有效");

  // ---- 6. 重复调用清理（幂等） ----
  实例1.手动清理();
  实例1.手动清理();
  实例1.完成();
  断言(回调计数1 === 1, "结束回调只执行一次");

  // ---- 5. 主动中断后再次施法 ----
  const 实例3 = 创建战斗技能实例({ 技能键: "测试技能", 施法者, 数据: { 序号: 3 } });
  实例3.中断();
  断言(实例3.结束原因 === "中断", "主动中断原因正确");
  const 实例4 = 创建战斗技能实例({ 技能键: "测试技能", 施法者 });
  断言(实例4.代次 === 实例3.代次 + 1, "中断后再施法代次 +1");

  // ---- 按实例 ID 查询 ----
  断言(按ID查询战斗技能实例(实例4.实例ID) === 实例4, "按实例ID查询");
  实例4.完成();
  断言(按ID查询战斗技能实例(实例4.实例ID) === null, "结束后按实例ID查询为空");

  // ---- 4. 目标先死亡 ----
  const 实例5 = 创建战斗技能实例({ 技能键: "带目标技能", 施法者, 目标 });
  jass.KillUnit(目标);
  断言(实例5.结束原因 === "目标死亡", "目标死亡自动收束");

  // ---- 3. 施法者死亡 ----
  const 实例6 = 创建战斗技能实例({ 技能键: "测试技能", 施法者 });
  const 实例7 = 创建战斗技能实例({ 技能键: "另一技能", 施法者 });
  jass.KillUnit(施法者);
  断言(实例6.结束原因 === "施法者死亡", "施法者死亡收束实例6");
  断言(实例7.结束原因 === "施法者死亡", "施法者死亡收束实例7（跨技能键）");

  // ---- 单位替换 / 战斗结束 ----
  const 施法者2 = jass.CreateUnit(jass.Player(0), 农民单位类型, 0, 100, 0);
  const 实例8 = 创建战斗技能实例({ 技能键: "替换测试", 施法者: 施法者2 });
  断言(实例8.施法者未替换() === true, "施法者句柄未替换");
  断言(校验单位替换并收束(施法者2) === 0, "未替换时不收束");
  const 数量 = 结束单位战斗技能实例(施法者2, "战斗结束");
  断言(数量 === 1 && 实例8.结束原因 === "战斗结束", "战斗结束统一收束");

  自检输出("全部自检项执行完毕（请核对上方通过/失败）");
}

export {};
