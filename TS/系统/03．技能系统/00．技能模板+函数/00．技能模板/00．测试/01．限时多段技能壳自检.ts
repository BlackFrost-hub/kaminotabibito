// 限时多段技能壳自检（默认关闭：不注册、不被任何模块导入）。
// 需要 JASS 真实单位句柄，进图环境手动调用 `运行多段技能壳自检(英雄)`。
// 逐项输出结果数组；token/超时项依赖进图时钟。

import {
  创建限时二段技能壳,
  确认限时二段技能壳,
  清理限时二段技能壳,
  开启多段技能窗口,
  确认多段技能阶段,
  清理多段技能壳,
  读取多段当前阶段,
} from "../../04．机制组件/10．复杂战斗通用机制/25．限时二段技能壳";

const jass = require("jass.common") as any;
const GetHandleId = jass.GetHandleId as (this: void, handle: any) => number;

// 测试用技能 ID（进图时替换为真实技能槽位）
const 一段ID = 111111;
const 二段ID = 222222;
const 三段ID = 333333;

function 断言(this: void, 结果: string[], 名称: string, 条件: boolean, 详情?: string): void {
  结果.push((条件 ? "PASS " : "FAIL ") + 名称 + (详情 != null ? " " + String(详情) : ""));
}

export function 运行多段技能壳自检(this: void, 英雄: any): string[] {
  const 结果: string[] = [];
  if (英雄 == null || 英雄 === 0) {
    结果.push("FAIL 无效测试单位");
    return 结果;
  }

  // 1. 二段兼容（旧 API 不回退）
  const 二段 = 创建限时二段技能壳({
    名称: "自检-二段",
    单位: 英雄,
    一段技能ID: 一段ID,
    二段技能ID: 二段ID,
    持续秒: 1,
  });
  断言(结果, "二段兼容-创建", 二段 != null);
  if (二段 != null) {
    断言(结果, "二段兼容-确认", 确认限时二段技能壳(二段));
    断言(结果, "二段兼容-重复确认幂等", 确认限时二段技能壳(二段) === false);
  }

  // 2. 三段顺序（确认 1 → 阶段2；确认 2 → 结束）
  const 三段 = 开启多段技能窗口({
    名称: "自检-三段",
    单位: 英雄,
    一段技能ID: 一段ID,
    阶段列表: [
      { 技能ID: 二段ID, 窗口秒: 1, 阶段魔耗: 0 },
      { 技能ID: 三段ID, 窗口秒: 1, 阶段魔耗: 0 },
    ],
  });
  断言(结果, "三段-开启", 三段 != null);
  if (三段 != null) {
    断言(结果, "三段-初始阶段0", 读取多段当前阶段(三段) === 0);
    断言(结果, "三段-确认1进阶段1", 确认多段技能阶段(三段) && 读取多段当前阶段(三段) === 1);
    断言(结果, "三段-确认2结束", 确认多段技能阶段(三段));
    断言(结果, "三段-结束后阶段-1", 读取多段当前阶段(三段) === -1);
    断言(结果, "三段-结束后再确认幂等", 确认多段技能阶段(三段) === false);
  }

  // 3. 重复开启 token（旧壳作废，新窗口不被旧清理关闭）
  const 甲 = 开启多段技能窗口({ 名称: "自检-token-甲", 单位: 英雄, 一段技能ID: 一段ID, 阶段列表: [{ 技能ID: 二段ID, 窗口秒: 5 }] });
  const 乙 = 开启多段技能窗口({ 名称: "自检-token-乙", 单位: 英雄, 一段技能ID: 一段ID, 阶段列表: [{ 技能ID: 三段ID, 窗口秒: 5 }] });
  断言(结果, "token-旧壳已结束", 甲 != null && 甲.已结束);
  断言(结果, "token-新壳激活", 乙 != null && !乙.已结束);
  if (乙 != null) 清理多段技能壳(乙);
  if (甲 != null) 清理多段技能壳(甲); // 幂等

  // 4. 主动清理
  const 丙 = 开启多段技能窗口({ 名称: "自检-清理", 单位: 英雄, 一段技能ID: 一段ID, 阶段列表: [{ 技能ID: 二段ID, 窗口秒: 5 }] });
  断言(结果, "清理-开启", 丙 != null);
  if (丙 != null) {
    断言(结果, "清理-主动清理", 清理多段技能壳(丙));
    断言(结果, "清理-重复清理幂等", 清理多段技能壳(丙) === false);
  }

  // 5. 死亡清理（进图时可用 KillUnit 验证；静态仅登记预期）
  结果.push("INFO 死亡清理: 开启多段壳后 KillUnit(英雄) 应自动复位，进图验证");
  结果.push("INFO 超时复位: 窗口秒=0.2 时应自动复位并触发窗口超时回调，进图验证");
  结果.push("INFO 阶段魔耗: 阶段魔耗=50 时确认阶段应扣 50 蓝，进图验证");

  return 结果;
}

export {};
