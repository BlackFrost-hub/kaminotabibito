import {
  创建延迟执行阶段,
  type 技能阶段定义,
  type 技能阶段链上下文,
  type 技能阶段控制器,
} from "../01．多阶段技能编排/06．技能阶段链执行器";

export interface 固定时间轴事件 {
  /** 从组合启动时刻起算的绝对毫秒时点。 */
  时点毫秒: number;
  名称?: string;
  执行: (this: void, 上下文: 技能阶段链上下文, 控制器: 技能阶段控制器) => void;
}
/** 将无序绝对时点事件稳定排序，并转换成阶段链需要的相对延迟阶段。 */
export function 创建固定时间轴阶段列表(this: void, 事件列表: 固定时间轴事件[]): 技能阶段定义[] {
  const 排序后: 固定时间轴事件[] = [];
  for (let i = 0; i < 事件列表.length; i++) {
    const 事件 = 事件列表[i];
    let 插入位置 = 排序后.length;
    while (插入位置 > 0 && 排序后[插入位置 - 1].时点毫秒 > 事件.时点毫秒) {
      插入位置 -= 1;
    }
    排序后.splice(插入位置, 0, 事件);
  }

  const 阶段列表: 技能阶段定义[] = [];
  let 上一时点毫秒 = 0;
  for (let i = 0; i < 排序后.length; i++) {
    const 事件 = 排序后[i];
    const 当前时点毫秒 = 事件.时点毫秒 > 0 ? 事件.时点毫秒 : 0;
    const 延迟毫秒 = 当前时点毫秒 - 上一时点毫秒;
    阶段列表.push(创建延迟执行阶段(延迟毫秒 > 0 ? 延迟毫秒 : 0, 事件.执行, 事件.名称));
    上一时点毫秒 = 当前时点毫秒;
  }
  return 阶段列表;
}
