const 世界地图单位缓存表: Record<string, any> = {};

function 是否匹配待缓存配置(
  this: void,
  出生配置: 世界地图单位出生配置,
  缓存配置: 世界地图待缓存单位配置,
): boolean {
  return 出生配置.分组名 === 缓存配置.分组名
    && 出生配置.单位名 === 缓存配置.单位名
    && 出生配置.X === 缓存配置.X
    && 出生配置.Y === 缓存配置.Y;
}

export function 尝试缓存世界地图单位(this: void, 出生配置: 世界地图单位出生配置, unit: any): void {
  if (unit == null || unit === 0) return;
  for (let i = 0; i < 世界地图待缓存单位配置表.length; i++) {
    const 缓存配置 = 世界地图待缓存单位配置表[i];
    if (!是否匹配待缓存配置(出生配置, 缓存配置)) continue;
    世界地图单位缓存表[缓存配置.缓存键] = unit;
    return;
  }
}

export function 消费世界地图单位缓存(this: void, 缓存键: string): any {
  if (缓存键 === "") return null;
  const unit = 世界地图单位缓存表[缓存键] ?? null;
  世界地图单位缓存表[缓存键] = undefined;
  delete 世界地图单位缓存表[缓存键];
  return unit;
}
