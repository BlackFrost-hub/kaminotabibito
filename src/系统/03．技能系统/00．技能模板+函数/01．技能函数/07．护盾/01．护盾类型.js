// 说明：
// - Lua 运行时对中文裸标识符不稳定，避免使用中文 enum 名。
// - 这里改成 ASCII 常量对象，再用中文名字导出，外部调用不变。
export { ShieldType as 护盾类型 };
export function 护盾属性转类型(属性) {
    if (属性 === "强化")
        return ShieldType.强化;
    if (属性 === "金")
        return ShieldType.金;
    if (属性 === "木")
        return ShieldType.木;
    if (属性 === "水")
        return ShieldType.水;
    if (属性 === "火")
        return ShieldType.火;
    if (属性 === "冰")
        return ShieldType.冰;
    if (属性 === "雷")
        return ShieldType.雷;
    if (属性 === "风")
        return ShieldType.风;
    if (属性 === "暗")
        return ShieldType.暗;
    if (属性 === "光")
        return ShieldType.光;
    if (属性 === "毒")
        return ShieldType.毒;
    return ShieldType.通用;
}
