/**
 * 处理护盾吸收（供伤害系统调用）
 *
 * @param 目标 受伤单位
 * @param 伤害值 待结算伤害
 * @param 是物理伤害 是否物理伤害
 * @param 是魔法伤害 是否魔法伤害
 * @param 攻击者 攻击者
 * @returns 剩余伤害
 */
export function 处理护盾吸收(目标, 伤害值, 是物理伤害, 是魔法伤害, 攻击者, 属性) {
    确保初始化();
    const 结果 = 吸收伤害(目标, 伤害值, 是物理伤害, 是魔法伤害, 攻击者, 属性);
    // 护盾条闪色反馈
    if (结果.总吸收量 > 0) {
        护盾条闪色(目标, 结果.闪色类型);
    }
    // 护盾破碎时检查是否需要删除护盾条
    if (结果.破碎护盾.length > 0) {
        const 单位ID = 取句柄ID(目标);
        if (!单位是否有护盾(单位ID)) {
            删除护盾条(目标);
        }
    }
    return 结果.剩余伤害;
}
