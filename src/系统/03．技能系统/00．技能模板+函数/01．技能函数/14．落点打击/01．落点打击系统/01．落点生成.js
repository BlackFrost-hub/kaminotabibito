import { GetRandomReal, } from "./00．共享";
const { CosBJ, SinBJ } = require("lib.扩展函数.BJ函数.12．数学函数");
function 计算两点距离平方(ax, ay, bx, by) {
    const dx = ax - bx;
    const dy = ay - by;
    return dx * dx + dy * dy;
}
function 计算落点最小间距(参数) {
    if (参数.最小落点间距 != null && 参数.最小落点间距 > 0) {
        return 参数.最小落点间距;
    }
    if ((参数.落点数量 ?? 1) <= 1) {
        return 0;
    }
    if (参数.伤害半径 <= 0) {
        return 0;
    }
    return 参数.伤害半径 * 0.45;
}
function 计算候选点到已有落点的最小距离平方(已有落点, 候选X, 候选Y) {
    if (已有落点.length <= 0) {
        return 999999999;
    }
    let 最小距离平方 = 999999999;
    for (const 已有落点信息 of 已有落点) {
        const 距离平方 = 计算两点距离平方(候选X, 候选Y, 已有落点信息.X, 已有落点信息.Y);
        if (距离平方 < 最小距离平方) {
            最小距离平方 = 距离平方;
        }
    }
    return 最小距离平方;
}
function 生成随机候选落点(中心X, 中心Y, 散布半径, 触发延迟) {
    if (散布半径 <= 0) {
        return { X: 中心X, Y: 中心Y, 触发延迟 };
    }
    while (true) {
        const 偏移X = GetRandomReal(-散布半径, 散布半径);
        const 偏移Y = GetRandomReal(-散布半径, 散布半径);
        if (偏移X * 偏移X + 偏移Y * 偏移Y > 散布半径 * 散布半径) {
            continue;
        }
        return {
            X: 中心X + 偏移X,
            Y: 中心Y + 偏移Y,
            触发延迟,
        };
    }
}
function 生成随机矩形候选落点(中心X, 中心Y, 长度, 宽度, 方向角, 触发延迟) {
    if (长度 <= 0 || 宽度 <= 0) {
        return { X: 中心X, Y: 中心Y, 触发延迟 };
    }
    const 前后偏移 = GetRandomReal(-长度 * 0.5, 长度 * 0.5);
    const 左右偏移 = GetRandomReal(-宽度 * 0.5, 宽度 * 0.5);
    const 前向X = CosBJ(方向角);
    const 前向Y = SinBJ(方向角);
    const 右向X = CosBJ(方向角 - 90);
    const 右向Y = SinBJ(方向角 - 90);
    return {
        X: 中心X + 前向X * 前后偏移 + 右向X * 左右偏移,
        Y: 中心Y + 前向Y * 前后偏移 + 右向Y * 左右偏移,
        触发延迟,
    };
}
function 生成单个落点(参数, 已有落点, 触发延迟) {
    const 随机区域形状 = 参数.随机区域形状 ?? "圆形";
    const 散布半径 = 参数.随机散布半径 != null && 参数.随机散布半径 > 0 ? 参数.随机散布半径 : 0;
    const 矩形长度 = 参数.随机矩形长度 != null && 参数.随机矩形长度 > 0 ? 参数.随机矩形长度 : 0;
    const 矩形宽度 = 参数.随机矩形宽度 != null && 参数.随机矩形宽度 > 0 ? 参数.随机矩形宽度 : 0;
    const 方向角 = 参数.随机区域方向角 ?? 0;
    if (随机区域形状 === "矩形") {
        if (矩形长度 <= 0 || 矩形宽度 <= 0) {
            return { X: 参数.X, Y: 参数.Y, 触发延迟 };
        }
    }
    else if (散布半径 <= 0) {
        return { X: 参数.X, Y: 参数.Y, 触发延迟 };
    }
    const 最小落点间距 = 计算落点最小间距(参数);
    const 最小落点间距平方 = 最小落点间距 * 最小落点间距;
    const 最大尝试次数 = 参数.随机取点最大尝试次数 != null && 参数.随机取点最大尝试次数 > 0
        ? 参数.随机取点最大尝试次数
        : 32;
    let 最佳候选 = 随机区域形状 === "矩形"
        ? 生成随机矩形候选落点(参数.X, 参数.Y, 矩形长度, 矩形宽度, 方向角, 触发延迟)
        : 生成随机候选落点(参数.X, 参数.Y, 散布半径, 触发延迟);
    let 最佳候选最小距离平方 = 计算候选点到已有落点的最小距离平方(已有落点, 最佳候选.X, 最佳候选.Y);
    let i = 1;
    while (i < 最大尝试次数) {
        const 候选 = 随机区域形状 === "矩形"
            ? 生成随机矩形候选落点(参数.X, 参数.Y, 矩形长度, 矩形宽度, 方向角, 触发延迟)
            : 生成随机候选落点(参数.X, 参数.Y, 散布半径, 触发延迟);
        const 候选最小距离平方 = 计算候选点到已有落点的最小距离平方(已有落点, 候选.X, 候选.Y);
        if (候选最小距离平方 >= 最小落点间距平方) {
            return 候选;
        }
        if (候选最小距离平方 > 最佳候选最小距离平方) {
            最佳候选 = 候选;
            最佳候选最小距离平方 = 候选最小距离平方;
        }
        i += 1;
    }
    return 最佳候选;
}
function 取落点与其他点的最小距离平方(落点列表, 序号) {
    const 当前落点 = 落点列表[序号];
    if (当前落点 == null) {
        return 0;
    }
    let 最小距离平方 = 999999999;
    let i = 0;
    while (i < 落点列表.length) {
        if (i !== 序号) {
            const 其他落点 = 落点列表[i];
            if (其他落点 != null) {
                const 距离平方 = 计算两点距离平方(当前落点.X, 当前落点.Y, 其他落点.X, 其他落点.Y);
                if (距离平方 < 最小距离平方) {
                    最小距离平方 = 距离平方;
                }
            }
        }
        i += 1;
    }
    return 最小距离平方;
}
function 轻度打散落点列表(参数, 落点列表) {
    if (落点列表.length <= 2) {
        return;
    }
    const 最小落点间距 = 计算落点最小间距(参数);
    if (最小落点间距 <= 0) {
        return;
    }
    const 目标距离平方 = 最小落点间距 * 最小落点间距;
    const 总轮数 = 2;
    const 单点重抽次数 = 8;
    let 轮次 = 0;
    while (轮次 < 总轮数) {
        let 最挤序号 = -1;
        let 最挤距离平方 = 999999999;
        let i = 0;
        while (i < 落点列表.length) {
            const 当前最小距离平方 = 取落点与其他点的最小距离平方(落点列表, i);
            if (当前最小距离平方 < 最挤距离平方) {
                最挤距离平方 = 当前最小距离平方;
                最挤序号 = i;
            }
            i += 1;
        }
        if (最挤序号 < 0 || 最挤距离平方 >= 目标距离平方) {
            return;
        }
        const 当前落点 = 落点列表[最挤序号];
        if (当前落点 == null) {
            return;
        }
        const 其他落点 = 落点列表.filter((_, 索引) => 索引 !== 最挤序号);
        let 最佳候选 = 当前落点;
        let 最佳候选距离平方 = 最挤距离平方;
        let j = 0;
        while (j < 单点重抽次数) {
            const 候选 = 生成单个落点(参数, 其他落点, 当前落点.触发延迟);
            const 候选距离平方 = 计算候选点到已有落点的最小距离平方(其他落点, 候选.X, 候选.Y);
            if (候选距离平方 > 最佳候选距离平方) {
                最佳候选 = 候选;
                最佳候选距离平方 = 候选距离平方;
                if (候选距离平方 >= 目标距离平方) {
                    break;
                }
            }
            j += 1;
        }
        落点列表[最挤序号] = 最佳候选;
        轮次 += 1;
    }
}
export function 创建落点列表(参数) {
    const 落点数量 = 参数.落点数量 != null && 参数.落点数量 > 0 ? 参数.落点数量 : 1;
    const 落点间隔 = 参数.落点间隔 != null && 参数.落点间隔 > 0 ? 参数.落点间隔 : 0;
    const 结果 = [];
    let i = 0;
    while (i < 落点数量) {
        结果.push(生成单个落点(参数, 结果, 参数.延迟时间 + i * 落点间隔));
        i += 1;
    }
    轻度打散落点列表(参数, 结果);
    return 结果;
}
