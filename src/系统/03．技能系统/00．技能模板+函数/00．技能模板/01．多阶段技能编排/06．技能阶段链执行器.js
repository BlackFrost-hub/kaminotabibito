/**
 * 技能阶段链执行器
 *
 * 说明：
 * 1. 用于“前摇 -> 执行 -> 再前摇 -> 再执行 -> 收尾”这类技能
 * 2. 当前提供最小高频复用能力：前摇阶段、引导阶段、立即执行阶段
 * 3. 可与生效帧 / 后摇 / 收尾模块组合使用
 */
import { 开始技能前摇, 停止技能前摇 } from "./01．前摇与持续施法";
import { 开始技能引导, 停止技能引导 } from "./05．技能引导阶段";
const 阶段链映射 = {};
let 下一个阶段链ID = 1;
function 创建阶段链上下文(运行时) {
    return {
        阶段链ID: 运行时.id,
        单位: 运行时.单位,
        数据: 运行时.数据,
        当前阶段索引: 运行时.当前阶段索引,
    };
}
function 完成阶段链(运行时, 原因) {
    if (运行时.已结束)
        return;
    运行时.已结束 = true;
    delete 阶段链映射[运行时.id];
    const 结束回调 = 运行时.结束回调;
    if (结束回调 != null) {
        结束回调(运行时.单位, 原因, 运行时.id, 创建阶段链上下文(运行时));
    }
}
function 进入下一阶段(运行时) {
    if (运行时.已结束)
        return;
    运行时.当前阶段停止函数 = undefined;
    运行时.当前阶段索引 += 1;
    if (运行时.当前阶段索引 >= 运行时.阶段列表.length) {
        完成阶段链(运行时, "完成");
        return;
    }
    const 当前阶段 = 运行时.阶段列表[运行时.当前阶段索引];
    const 控制器 = {
        完成当前阶段: function () {
            进入下一阶段(运行时);
        },
        中断阶段链: function (原因 = "中断") {
            停止技能阶段链(运行时.id, 原因);
        },
        设置当前阶段停止函数: function (fn) {
            运行时.当前阶段停止函数 = fn;
        },
        写入数据: function (key, value) {
            运行时.数据[key] = value;
        },
        读取数据: function (key) {
            return 运行时.数据[key];
        },
    };
    当前阶段.开始(创建阶段链上下文(运行时), 控制器);
}
export function 开始技能阶段链(单位, 阶段列表, 参数) {
    if (阶段列表.length <= 0)
        return 0;
    const 阶段链ID = 下一个阶段链ID++;
    const 运行时 = {
        id: 阶段链ID,
        单位,
        阶段列表,
        数据: 参数?.数据 ?? {},
        当前阶段索引: -1,
        已结束: false,
        结束回调: 参数?.结束回调,
    };
    阶段链映射[阶段链ID] = 运行时;
    进入下一阶段(运行时);
    return 阶段链ID;
}
export function 停止技能阶段链(阶段链ID, 原因 = "中断") {
    const 运行时 = 阶段链映射[阶段链ID];
    if (运行时 == null || 运行时.已结束)
        return false;
    const 停止函数 = 运行时.当前阶段停止函数;
    if (停止函数 != null) {
        运行时.当前阶段停止函数 = undefined;
        停止函数(原因);
    }
    完成阶段链(运行时, 原因);
    return true;
}
export function 创建立即执行阶段(执行, 名称) {
    return {
        名称,
        开始: function (上下文, 控制器) {
            执行(上下文, 控制器);
            控制器.完成当前阶段();
        },
    };
}
export function 创建前摇阶段(参数) {
    return {
        名称: 参数.名称,
        开始: function (上下文, 控制器) {
            const 原完成后执行 = 参数.完成后执行;
            const 原结束回调 = 参数.结束回调;
            const 阶段参数 = { ...参数 };
            阶段参数.完成后执行 = function (单位, 前摇ID) {
                if (原完成后执行 != null) {
                    原完成后执行(单位, 前摇ID);
                }
                控制器.完成当前阶段();
            };
            阶段参数.结束回调 = function (单位, 原因, 前摇ID) {
                if (原结束回调 != null) {
                    原结束回调(单位, 原因, 前摇ID);
                }
                if (原因 !== "完成") {
                    控制器.中断阶段链(原因);
                }
            };
            const 阶段ID = 开始技能前摇(上下文.单位, 阶段参数);
            控制器.设置当前阶段停止函数(function () {
                停止技能前摇(阶段ID);
            });
        },
    };
}
export function 创建引导阶段(参数) {
    return {
        名称: 参数.名称,
        开始: function (上下文, 控制器) {
            const 原完成回调 = 参数.完成回调;
            const 原结束回调 = 参数.结束回调;
            const 阶段参数 = { ...参数 };
            阶段参数.完成回调 = function (单位, 引导ID) {
                if (原完成回调 != null) {
                    原完成回调(单位, 引导ID);
                }
                控制器.完成当前阶段();
            };
            阶段参数.结束回调 = function (单位, 原因, 引导ID) {
                if (原结束回调 != null) {
                    原结束回调(单位, 原因, 引导ID);
                }
                if (原因 !== "完成") {
                    控制器.中断阶段链(原因);
                }
            };
            const 阶段ID = 开始技能引导(上下文.单位, 阶段参数);
            控制器.设置当前阶段停止函数(function (原因) {
                停止技能引导(阶段ID, 原因);
            });
        },
    };
}
