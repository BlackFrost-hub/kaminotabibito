let 已初始化物品主动技能核心 = false;
function 施法单位是英雄(上下文) {
    const 单位 = 上下文.施法单位;
    return 单位 != null && 单位 !== 0 && IsUnitType(单位, UNIT_TYPE_HERO) === true;
}
function on物品主动技能生效(上下文) {
    if (!施法单位是英雄(上下文))
        return;
    处理破血之戒使用(上下文);
    处理远古毒咒护符使用(上下文);
    处理史莱姆粘液瓶使用(上下文);
    处理地精钥匙使用(上下文);
    处理祭祀之杖使用(上下文);
    处理幽冥法杖使用(上下文);
    处理熔岩恶魔之灵眼使用(上下文);
    处理暗幽亡戒使用(上下文);
    处理使者魔炉使用(上下文);
    处理汭冥血杖使用(上下文);
    处理汭冥血杖强化使用(上下文);
    处理使者精神魔杖使用(上下文);
    处理史诗远古魔刃使用(上下文);
    处理焰虚宝珠使用(上下文);
    处理先祖之狱杖使用(上下文);
    处理咆哮之心使用(上下文);
    处理指挥之剑使用(上下文);
    处理使者魔轮使用(上下文);
}
export function 初始化物品主动技能核心() {
    if (已初始化物品主动技能核心)
        return;
    已初始化物品主动技能核心 = true;
    注册物品技能事件监听(on物品主动技能生效);
}
